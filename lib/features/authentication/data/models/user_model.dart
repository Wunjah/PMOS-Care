import '../../domain/entities/user_entity.dart';

class UserModel extends UserEntity {
  const UserModel({
    required super.uid,
    required super.phoneNumber,
    super.email,
    required super.displayName,
    super.photoUrl,
    required super.isOnboardingCompleted,
    super.role = 'patient',
    super.age,
    super.heightCm,
    super.weightKg,
    super.country,
    super.region,
    super.pmosDiagnosisStatus,
    super.medications,
    super.allergies,
    super.goals,
    super.specialty,
    super.hospitalClinic,
    super.yearsExperience,
    super.licenseNumber,
    super.skinAcneSeverity,
    super.skinAffectedAreas,
    super.syncHeartRate,
    super.syncDailySteps,
    super.syncBloodGlucose,
    super.googleFitConnected,
    super.biometricLockEnabled,
    super.notificationsEnabled,
  });

  factory UserModel.fromJson(Map<String, dynamic> json) {
    return UserModel(
      uid: json['uid'] as String,
      phoneNumber: json['phoneNumber'] as String? ?? '',
      email: json['email'] as String?,
      displayName: json['displayName'] as String? ?? '',
      photoUrl: json['photoUrl'] as String?,
      isOnboardingCompleted: json['isOnboardingCompleted'] as bool? ?? false,
      role: json['role'] as String? ?? 'patient',
      age: json['age'] as int?,
      heightCm: (json['heightCm'] as num?)?.toDouble(),
      weightKg: (json['weightKg'] as num?)?.toDouble(),
      country: json['country'] as String?,
      region: json['region'] as String?,
      pmosDiagnosisStatus: json['pmosDiagnosisStatus'] as String?,
      medications: List<String>.from(json['medications'] as List? ?? []),
      allergies: List<String>.from(json['allergies'] as List? ?? []),
      goals: List<String>.from(json['goals'] as List? ?? []),
      specialty: json['specialty'] as String?,
      hospitalClinic: json['hospitalClinic'] as String?,
      yearsExperience: json['yearsExperience'] as int?,
      licenseNumber: json['licenseNumber'] as String?,
      skinAcneSeverity: json['skinAcneSeverity'] as String?,
      skinAffectedAreas: List<String>.from(json['skinAffectedAreas'] as List? ?? []),
      syncHeartRate: json['syncHeartRate'] as bool? ?? true,
      syncDailySteps: json['syncDailySteps'] as bool? ?? true,
      syncBloodGlucose: json['syncBloodGlucose'] as bool? ?? false,
      googleFitConnected: json['googleFitConnected'] as bool? ?? false,
      biometricLockEnabled: json['biometricLockEnabled'] as bool? ?? false,
      notificationsEnabled: json['notificationsEnabled'] as bool? ?? false,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'uid': uid,
      'phoneNumber': phoneNumber,
      'email': email,
      'displayName': displayName,
      'photoUrl': photoUrl,
      'isOnboardingCompleted': isOnboardingCompleted,
      'role': role,
      'age': age,
      'heightCm': heightCm,
      'weightKg': weightKg,
      'country': country,
      'region': region,
      'pmosDiagnosisStatus': pmosDiagnosisStatus,
      'medications': medications,
      'allergies': allergies,
      'goals': goals,
      'specialty': specialty,
      'hospitalClinic': hospitalClinic,
      'yearsExperience': yearsExperience,
      'licenseNumber': licenseNumber,
      'skinAcneSeverity': skinAcneSeverity,
      'skinAffectedAreas': skinAffectedAreas,
      'syncHeartRate': syncHeartRate,
      'syncDailySteps': syncDailySteps,
      'syncBloodGlucose': syncBloodGlucose,
      'googleFitConnected': googleFitConnected,
      'biometricLockEnabled': biometricLockEnabled,
      'notificationsEnabled': notificationsEnabled,
    };
  }

  factory UserModel.fromEntity(UserEntity entity) {
    return UserModel(
      uid: entity.uid,
      phoneNumber: entity.phoneNumber,
      email: entity.email,
      displayName: entity.displayName,
      photoUrl: entity.photoUrl,
      isOnboardingCompleted: entity.isOnboardingCompleted,
      role: entity.role,
      age: entity.age,
      heightCm: entity.heightCm,
      weightKg: entity.weightKg,
      country: entity.country,
      region: entity.region,
      pmosDiagnosisStatus: entity.pmosDiagnosisStatus,
      medications: entity.medications,
      allergies: entity.allergies,
      goals: entity.goals,
      specialty: entity.specialty,
      hospitalClinic: entity.hospitalClinic,
      yearsExperience: entity.yearsExperience,
      licenseNumber: entity.licenseNumber,
      skinAcneSeverity: entity.skinAcneSeverity,
      skinAffectedAreas: entity.skinAffectedAreas,
      syncHeartRate: entity.syncHeartRate,
      syncDailySteps: entity.syncDailySteps,
      syncBloodGlucose: entity.syncBloodGlucose,
      googleFitConnected: entity.googleFitConnected,
      biometricLockEnabled: entity.biometricLockEnabled,
      notificationsEnabled: entity.notificationsEnabled,
    );
  }
}
